import {
  ArrowUpDown,
  Check,
  Copy,
  Database,
  Flame,
  GitBranch,
  Layers,
  MessageSquareQuote,
  RotateCcw,
  Search,
  SlidersHorizontal,
  Sparkles,
  Star,
  X,
} from 'lucide-react';
import { useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState } from 'react';
import type { CSSProperties } from 'react';
import { FilterPanel } from './components/FilterPanel';
import { RuleDetailDialog } from './components/RuleDetailDialog';
import { ThemeSwitcher } from './components/ThemeSwitcher';
import { ToastRegion } from './components/ToastRegion';
import { useLocalStorage } from './hooks/useLocalStorage';
import {
  AGENT_LABELS,
  ALL_AGENTS,
  ALL_CATEGORIES,
  type CanonicalRule,
  type FilterState,
  type MinAdoption,
  type RuleDataset,
  type SortOption,
  type ThemeId,
} from './types';

const DEFAULT_FILTERS: FilterState = {
  query: '',
  agents: [],
  categories: [],
  minAdoption: 0,
  sort: 'repos',
};

const SORT_OPTIONS: { id: SortOption; label: string; icon: typeof GitBranch }[] = [
  { id: 'repos', label: 'Most Repos', icon: GitBranch },
  { id: 'weighted', label: 'Star-Weighted', icon: Star },
  { id: 'trending', label: 'Trending / Recent', icon: Flame },
];

function applyThemeToDocument(theme: ThemeId): void {
  document.documentElement.dataset.theme = theme;
  const scheme = theme === 'dark' || theme === 'terminal' ? 'dark' : 'light';
  const meta = document.querySelector('meta[name="color-scheme"]');
  if (meta) {
    meta.setAttribute('content', scheme);
  }
}

export function App() {
  const [dataset, setDataset] = useState<RuleDataset | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const [theme, setTheme] = useLocalStorage<ThemeId>('ruleindex:theme', 'light');
  const [filters, setFilters] = useLocalStorage<FilterState>('ruleindex:filters', DEFAULT_FILTERS);

  const [selectedRule, setSelectedRule] = useState<{ rule: CanonicalRule; rank: number } | null>(null);
  const [copiedId, setCopiedId] = useState<string | null>(null);
  const [toastMessage, setToastMessage] = useState<string | null>(null);
  const [mobileDrawerOpen, setMobileDrawerOpen] = useState(false);

  const mobileDrawerRef = useRef<HTMLDialogElement>(null);
  const rulesListRef = useRef<HTMLOListElement>(null);
  const [tenRulesHeight, setTenRulesHeight] = useState<number | null>(null);

  // Sync theme to document & <meta name="color-scheme">
  useEffect(() => {
    applyThemeToDocument(theme);
  }, [theme]);

  // Keep native mobile filter <dialog> synced with state
  useEffect(() => {
    const drawer = mobileDrawerRef.current;
    if (!drawer) return;
    if (mobileDrawerOpen && !drawer.open) {
      drawer.showModal();
    } else if (!mobileDrawerOpen && drawer.open) {
      drawer.close();
    }
  }, [mobileDrawerOpen]);

  // Light-dismiss fallback for mobile filter drawer when closedby is unsupported
  useEffect(() => {
    const drawer = mobileDrawerRef.current;
    if (!drawer || 'closedBy' in HTMLDialogElement.prototype) return;

    const isOutside = (e: PointerEvent) => {
      const rect = drawer.getBoundingClientRect();
      return (
        e.clientX < rect.left ||
        e.clientX > rect.right ||
        e.clientY < rect.top ||
        e.clientY > rect.bottom
      );
    };

    let pressedOutside = false;
    const onDown = (e: PointerEvent) => {
      pressedOutside = isOutside(e);
    };
    const onUp = (e: PointerEvent) => {
      if (pressedOutside && isOutside(e)) drawer.close();
      pressedOutside = false;
    };
    drawer.addEventListener('pointerdown', onDown);
    drawer.addEventListener('pointerup', onUp);
    return () => {
      drawer.removeEventListener('pointerdown', onDown);
      drawer.removeEventListener('pointerup', onUp);
    };
  }, []);

  // Load static JSON dataset generated by the Python pipeline
  useEffect(() => {
    let cancelled = false;
    const dataUrl = `${import.meta.env.BASE_URL}data/rules.json`;

    fetch(dataUrl)
      .then((resp) => {
        if (!resp.ok) throw new Error(`Failed to load dataset (${resp.status})`);
        return resp.json() as Promise<RuleDataset>;
      })
      .then((json) => {
        if (!cancelled) {
          setDataset(json);
          setLoading(false);
        }
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          setError(err instanceof Error ? err.message : 'Unable to load rules dataset.');
          setLoading(false);
        }
      });

    return () => {
      cancelled = true;
    };
  }, []);

  const rules = dataset?.rules ?? [];

  // Facet counts across all rules
  const agentCounts = useMemo(() => {
    const counts: Record<string, number> = {};
    for (const agent of ALL_AGENTS) counts[agent] = 0;
    for (const rule of rules) {
      for (const agent of rule.agents) {
        counts[agent] = (counts[agent] ?? 0) + 1;
      }
    }
    return counts;
  }, [rules]);

  const categoryCounts = useMemo(() => {
    const counts: Record<string, number> = {};
    for (const cat of ALL_CATEGORIES) counts[cat] = 0;
    for (const rule of rules) {
      counts[rule.category] = (counts[rule.category] ?? 0) + 1;
    }
    return counts;
  }, [rules]);

  const filteredRules = useMemo(() => {
    const q = filters.query.trim().toLowerCase();

    const matched = rules.filter((rule) => {
      if (rule.adoption_count < filters.minAdoption) return false;

      if (filters.agents.length > 0 && !filters.agents.some((a) => rule.agents.includes(a))) {
        return false;
      }

      if (filters.categories.length > 0 && !filters.categories.includes(rule.category)) {
        return false;
      }

      if (q) {
        const haystack = [
          rule.title,
          rule.summary,
          rule.category,
          ...rule.agents,
          ...rule.examples.map((e) => `${e.text} ${e.repo}`),
        ]
          .join(' ')
          .toLowerCase();
        if (!haystack.includes(q)) return false;
      }

      return true;
    });

    return [...matched].sort((a, b) => {
      if (filters.sort === 'weighted') {
        return b.weighted_score - a.weighted_score || b.adoption_count - a.adoption_count;
      }
      if (filters.sort === 'trending') {
        const dateDiff = new Date(b.first_seen).getTime() - new Date(a.first_seen).getTime();
        if (dateDiff !== 0) return dateDiff;
        return b.weighted_score - a.weighted_score;
      }
      return b.adoption_count - a.adoption_count || b.weighted_score - a.weighted_score;
    });
  }, [filters, rules]);

  const activeFilterCount =
    filters.agents.length +
    filters.categories.length +
    (filters.minAdoption > 0 ? 1 : 0) +
    (filters.query.trim() ? 1 : 0);

  const hasActiveFilters = activeFilterCount > 0;

  const toggleAgent = useCallback(
    (agent: string) => {
      setFilters((prev) => ({
        ...prev,
        agents: prev.agents.includes(agent)
          ? prev.agents.filter((a) => a !== agent)
          : [...prev.agents, agent],
      }));
    },
    [setFilters]
  );

  const clearAgents = useCallback(() => {
    setFilters((prev) => ({ ...prev, agents: [] }));
  }, [setFilters]);

  const toggleCategory = useCallback(
    (category: string) => {
      setFilters((prev) => ({
        ...prev,
        categories: prev.categories.includes(category)
          ? prev.categories.filter((c) => c !== category)
          : [...prev.categories, category],
      }));
    },
    [setFilters]
  );

  const setMinAdoption = useCallback(
    (minAdoption: MinAdoption) => {
      setFilters((prev) => ({ ...prev, minAdoption }));
    },
    [setFilters]
  );

  const setSort = useCallback(
    (sort: SortOption) => {
      setFilters((prev) => ({ ...prev, sort }));
    },
    [setFilters]
  );

  const resetFilters = useCallback(() => {
    setFilters((prev) => ({
      ...DEFAULT_FILTERS,
      sort: prev.sort,
    }));
  }, [setFilters]);

  const handleCopyRule = useCallback((rule: CanonicalRule) => {
    const markdown = `- **${rule.title}**: ${rule.summary}`;
    const showSuccess = () => {
      setCopiedId(rule.id);
      setToastMessage('Copied markdown rule to clipboard');
      window.setTimeout(() => {
        setCopiedId((cur) => (cur === rule.id ? null : cur));
      }, 1800);
    };

    if (navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {
      navigator.clipboard.writeText(markdown).then(showSuccess).catch(() => {
        setToastMessage('Could not access clipboard');
      });
    } else {
      const textarea = document.createElement('textarea');
      textarea.value = markdown;
      textarea.style.position = 'fixed';
      textarea.style.opacity = '0';
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand('copy');
      document.body.removeChild(textarea);
      showSuccess();
    }
  }, []);

  const updatedLabel = useMemo(() => {
    if (!dataset?.generated_at) return 'Daily sync';
    try {
      return new Intl.DateTimeFormat('en-US', {
        month: 'short',
        day: 'numeric',
        year: 'numeric',
      }).format(new Date(dataset.generated_at));
    } catch {
      return dataset.generated_at.slice(0, 10);
    }
  }, [dataset?.generated_at]);

  // Measure the rendered height of the first 10 rules so the scrollbox displays at least 10 rules
  // or fits the viewport height, whichever is larger.
  useLayoutEffect(() => {
    const listEl = rulesListRef.current;
    if (!listEl || filteredRules.length <= 10) {
      setTenRulesHeight(null);
      return;
    }

    const measure = () => {
      const items = listEl.children;
      if (items.length < 10) return;
      const firstRect = items[0].getBoundingClientRect();
      const tenthRect = items[9].getBoundingClientRect();
      const span = Math.ceil(tenthRect.bottom - firstRect.top + 32);
      if (span > 0) {
        setTenRulesHeight(span);
      }
    };

    measure();
    if (typeof ResizeObserver === 'undefined') return;
    const ro = new ResizeObserver(measure);
    ro.observe(listEl);
    return () => ro.disconnect();
  }, [filteredRules]);

  return (
    <div className="min-h-screen flex flex-col">
      {/* Sticky Top Header */}
      <header
        className="sticky top-0 z-30 border-b backdrop-blur-md"
        style={{
          backgroundColor: 'color-mix(in srgb, var(--bg-surface) 90%, transparent)',
          borderColor: 'var(--border-subtle)',
        }}
      >
        <div className="mx-auto flex max-w-7xl items-center justify-between gap-3 px-4 py-3 sm:px-6">
          <div className="flex items-center gap-2.5 min-w-0">
            <div
              className="flex h-9 w-9 shrink-0 items-center justify-center rounded-xl font-bold shadow-sm"
              style={{ backgroundColor: 'var(--accent)', color: '#ffffff' }}
              aria-hidden="true"
            >
              <Sparkles className="h-5 w-5" />
            </div>
            <div className="min-w-0">
              <div className="flex items-center gap-2">
                <span className="text-base font-bold tracking-tight sm:text-lg" style={{ color: 'var(--text-primary)' }}>
                  RuleIndex
                </span>
                <span
                  className="hidden rounded-full px-2 py-0.5 text-[11px] font-semibold sm:inline-flex"
                  style={{ backgroundColor: 'var(--accent-soft)', color: 'var(--accent-text)' }}
                >
                  Daily Distilled
                </span>
              </div>
              <p className="hidden truncate text-xs md:block" style={{ color: 'var(--text-muted)' }}>
                Canonical AI coding agent rules clustered from public GitHub repositories
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <ThemeSwitcher theme={theme} onChange={setTheme} />
            <button
              type="button"
              onClick={() => setMobileDrawerOpen(true)}
              aria-label="Open filters"
              aria-expanded={mobileDrawerOpen}
              className="inline-flex min-h-9 items-center gap-1.5 rounded-lg border px-3 py-1.5 text-xs font-semibold lg:hidden cursor-pointer"
              style={{
                backgroundColor: 'var(--bg-subtle)',
                borderColor: 'var(--border-subtle)',
                color: 'var(--text-primary)',
              }}
            >
              <SlidersHorizontal className="h-4 w-4" aria-hidden="true" />
              <span>Filters</span>
              {activeFilterCount > 0 && (
                <span
                  className="inline-flex h-5 min-w-5 items-center justify-center rounded-full px-1 text-[11px] font-bold"
                  style={{ backgroundColor: 'var(--accent)', color: '#ffffff' }}
                >
                  {activeFilterCount}
                </span>
              )}
            </button>
          </div>
        </div>
      </header>

      {/* Main Content */}
      <main className="mx-auto w-full max-w-7xl flex-1 px-4 py-6 sm:px-6 lg:py-8">
        {/* Compact Hero Stats Strip */}
        <section
          aria-label="Dataset summary"
          className="mb-6 grid grid-cols-2 gap-3 rounded-2xl border p-4 sm:grid-cols-4 sm:gap-4"
          style={{
            backgroundColor: 'var(--bg-surface)',
            borderColor: 'var(--border-subtle)',
          }}
        >
          <div className="flex flex-col gap-0.5">
            <span className="text-xs font-medium" style={{ color: 'var(--text-muted)' }}>
              Canonical Rules
            </span>
            <span className="text-xl font-bold tabular-nums sm:text-2xl" style={{ color: 'var(--text-primary)' }}>
              {dataset ? dataset.stats.total_rules.toLocaleString() : '—'}
            </span>
          </div>
          <div className="flex flex-col gap-0.5">
            <span className="text-xs font-medium" style={{ color: 'var(--text-muted)' }}>
              Repos Indexed
            </span>
            <span className="text-xl font-bold tabular-nums sm:text-2xl" style={{ color: 'var(--text-primary)' }}>
              {dataset ? `${dataset.stats.total_repos_indexed.toLocaleString()}+` : '—'}
            </span>
          </div>
          <div className="flex flex-col gap-0.5">
            <span className="text-xs font-medium" style={{ color: 'var(--text-muted)' }}>
              Agent Systems
            </span>
            <span className="text-xl font-bold tabular-nums sm:text-2xl" style={{ color: 'var(--text-primary)' }}>
              {ALL_AGENTS.length}
            </span>
          </div>
          <div className="flex flex-col gap-0.5">
            <span className="text-xs font-medium" style={{ color: 'var(--text-muted)' }}>
              Last Updated
            </span>
            <span className="inline-flex items-center gap-1.5 text-sm font-semibold sm:text-base" style={{ color: 'var(--text-primary)' }}>
              <Database className="h-4 w-4 shrink-0" style={{ color: 'var(--accent)' }} aria-hidden="true" />
              {updatedLabel}
            </span>
          </div>
        </section>

        <div className="flex flex-col gap-6 lg:flex-row lg:items-start">
          {/* Desktop Sticky Sidebar */}
          <aside
            aria-label="Rule filters"
            className="hidden w-72 shrink-0 rounded-2xl border p-5 lg:sticky lg:top-20 lg:block lg:max-h-[calc(100vh-6rem)] lg:overflow-y-auto"
            style={{
              backgroundColor: 'var(--bg-surface)',
              borderColor: 'var(--border-subtle)',
            }}
          >
            <FilterPanel
              filters={filters}
              agentCounts={agentCounts}
              categoryCounts={categoryCounts}
              hasActiveFilters={hasActiveFilters}
              onToggleAgent={toggleAgent}
              onClearAgents={clearAgents}
              onToggleCategory={toggleCategory}
              onSetMinAdoption={setMinAdoption}
              onReset={resetFilters}
            />
          </aside>

          {/* Leaderboard Column */}
          <div className="min-w-0 flex-1">
            {/* Search & Sort Controls */}
            <div
              className="mb-4 flex flex-col gap-3 rounded-2xl border p-3.5 sm:p-4"
              style={{
                backgroundColor: 'var(--bg-surface)',
                borderColor: 'var(--border-subtle)',
              }}
            >
              <div className="flex flex-col gap-3 md:flex-row md:items-center">
                <div className="relative flex-1">
                  <Search
                    className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2"
                    style={{ color: 'var(--text-muted)' }}
                    aria-hidden="true"
                  />
                  <input
                    type="search"
                    value={filters.query}
                    onChange={(e) => setFilters((prev) => ({ ...prev, query: e.target.value }))}
                    placeholder="Search rules, conventions, agents, or repos (e.g. secrets, TypeScript, pytest)..."
                    aria-label="Search distilled rules"
                    className="min-h-10 w-full rounded-xl border py-2 pl-9 pr-9 text-sm"
                    style={{
                      backgroundColor: 'var(--bg-subtle)',
                      borderColor: 'var(--border-subtle)',
                      color: 'var(--text-primary)',
                    }}
                  />
                  {filters.query && (
                    <button
                      type="button"
                      onClick={() => setFilters((prev) => ({ ...prev, query: '' }))}
                      aria-label="Clear search query"
                      className="absolute right-2.5 top-1/2 -translate-y-1/2 rounded p-1 cursor-pointer"
                      style={{ color: 'var(--text-muted)' }}
                    >
                      <X className="h-4 w-4" aria-hidden="true" />
                    </button>
                  )}
                </div>

                {/* Sort Toggles */}
                <div
                  role="group"
                  aria-label="Sort leaderboard"
                  className="inline-flex flex-wrap items-center gap-1 rounded-xl border p-1"
                  style={{
                    backgroundColor: 'var(--bg-subtle)',
                    borderColor: 'var(--border-subtle)',
                  }}
                >
                  <span className="sr-only">Sort by</span>
                  {SORT_OPTIONS.map((opt) => {
                    const Icon = opt.icon;
                    const active = filters.sort === opt.id;
                    return (
                      <button
                        key={opt.id}
                        type="button"
                        onClick={() => setSort(opt.id)}
                        aria-pressed={active}
                        className="inline-flex min-h-8 flex-1 items-center justify-center gap-1.5 rounded-lg px-2.5 py-1 text-xs font-semibold transition-colors whitespace-nowrap cursor-pointer sm:flex-initial"
                        style={
                          active
                            ? {
                                backgroundColor: 'var(--bg-surface)',
                                color: 'var(--text-primary)',
                                boxShadow: '0 1px 2px rgba(0,0,0,0.08)',
                              }
                            : { color: 'var(--text-secondary)' }
                        }
                      >
                        <Icon className="h-3.5 w-3.5" aria-hidden="true" />
                        {opt.label}
                      </button>
                    );
                  })}
                </div>
              </div>

              {/* Active Filter Pills & Live Result Count */}
              <div className="flex flex-wrap items-center justify-between gap-2 pt-1">
                <div className="flex flex-wrap items-center gap-1.5">
                  <span className="inline-flex items-center gap-1.5 text-xs font-medium" style={{ color: 'var(--text-muted)' }}>
                    <ArrowUpDown className="h-3.5 w-3.5" aria-hidden="true" />
                    Showing <strong style={{ color: 'var(--text-primary)' }}>{filteredRules.length}</strong> of{' '}
                    {rules.length} distilled rules
                  </span>

                  {filters.agents.map((agent) => (
                    <button
                      key={`pill-agent-${agent}`}
                      type="button"
                      onClick={() => toggleAgent(agent)}
                      className="inline-flex items-center gap-1 rounded-full px-2.5 py-0.5 text-xs font-medium cursor-pointer"
                      style={{ backgroundColor: 'var(--accent-soft)', color: 'var(--accent-text)' }}
                    >
                      <span>{AGENT_LABELS[agent] ?? agent}</span>
                      <X className="h-3 w-3" aria-hidden="true" />
                    </button>
                  ))}

                  {filters.categories.map((cat) => (
                    <button
                      key={`pill-cat-${cat}`}
                      type="button"
                      onClick={() => toggleCategory(cat)}
                      className="inline-flex items-center gap-1 rounded-full px-2.5 py-0.5 text-xs font-medium cursor-pointer"
                      style={{ backgroundColor: 'var(--accent-soft)', color: 'var(--accent-text)' }}
                    >
                      <span>{cat}</span>
                      <X className="h-3 w-3" aria-hidden="true" />
                    </button>
                  ))}

                  {filters.minAdoption > 0 && (
                    <button
                      type="button"
                      onClick={() => setMinAdoption(0)}
                      className="inline-flex items-center gap-1 rounded-full px-2.5 py-0.5 text-xs font-medium cursor-pointer"
                      style={{ backgroundColor: 'var(--accent-soft)', color: 'var(--accent-text)' }}
                    >
                      <span>{filters.minAdoption}+ repos</span>
                      <X className="h-3 w-3" aria-hidden="true" />
                    </button>
                  )}
                </div>

                {hasActiveFilters && (
                  <button
                    type="button"
                    onClick={resetFilters}
                    className="inline-flex items-center gap-1 rounded-lg px-2 py-1 text-xs font-semibold cursor-pointer hover:underline"
                    style={{ color: 'var(--accent-text)' }}
                  >
                    <RotateCcw className="h-3 w-3" aria-hidden="true" />
                    Reset Filters
                  </button>
                )}
              </div>
            </div>

            {/* Loading / Error / Empty / Leaderboard */}
            {loading ? (
              <div className="flex flex-col gap-3">
                {[1, 2, 3, 4, 5].map((i) => (
                  <div
                    key={i}
                    className="h-32 animate-pulse rounded-2xl border"
                    style={{
                      backgroundColor: 'var(--bg-surface)',
                      borderColor: 'var(--border-subtle)',
                    }}
                  />
                ))}
              </div>
            ) : error ? (
              <div
                className="rounded-2xl border p-8 text-center"
                style={{
                  backgroundColor: 'var(--bg-surface)',
                  borderColor: 'var(--border-strong)',
                }}
              >
                <p className="text-sm font-semibold" style={{ color: 'var(--text-primary)' }}>
                  Failed to load RuleIndex dataset
                </p>
                <p className="mt-1 text-xs" style={{ color: 'var(--text-muted)' }}>
                  {error}
                </p>
              </div>
            ) : filteredRules.length === 0 ? (
              <div
                className="rounded-2xl border p-10 text-center"
                style={{
                  backgroundColor: 'var(--bg-surface)',
                  borderColor: 'var(--border-subtle)',
                }}
              >
                <Layers className="mx-auto h-8 w-8" style={{ color: 'var(--text-muted)' }} aria-hidden="true" />
                <p className="mt-3 text-base font-semibold" style={{ color: 'var(--text-primary)' }}>
                  No matching rules found
                </p>
                <p className="mt-1 text-sm" style={{ color: 'var(--text-secondary)' }}>
                  Try broadening your search query or clearing one of your active filters.
                </p>
                <button
                  type="button"
                  onClick={resetFilters}
                  className="mt-4 inline-flex min-h-10 items-center gap-1.5 rounded-xl px-4 py-2 text-sm font-semibold cursor-pointer"
                  style={{ backgroundColor: 'var(--accent)', color: '#ffffff' }}
                >
                  <RotateCcw className="h-4 w-4" aria-hidden="true" />
                  Reset Filters
                </button>
              </div>
            ) : (
              <div
                className="rules-scrollbox rounded-2xl border p-3 sm:p-4"
                data-fits-all={filteredRules.length <= 10 ? 'true' : 'false'}
                tabIndex={0}
                aria-label={`Ranked AI coding agent rules (${filteredRules.length} total)`}
                style={
                  {
                    backgroundColor: 'var(--bg-subtle)',
                    borderColor: 'var(--border-subtle)',
                    ...(tenRulesHeight !== null ? { '--ten-rules-height': `${tenRulesHeight}px` } : {}),
                  } as CSSProperties
                }
              >
                <ol
                  ref={rulesListRef}
                  className="flex flex-col gap-3"
                  aria-label="Ranked AI coding agent rules"
                >
                  {filteredRules.map((rule, index) => {
                    const rank = index + 1;
                    const isCopied = copiedId === rule.id;

                    return (
                      <li
                        key={rule.id}
                        className="rules-scrollbox-item rounded-2xl border p-4 transition-colors sm:p-5"
                        style={{
                          backgroundColor: 'var(--bg-surface)',
                          borderColor: 'var(--border-subtle)',
                        }}
                      >
                      <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
                        {/* Rank + Main Rule Info */}
                        <div className="flex items-start gap-3.5 min-w-0 flex-1">
                          <span
                            className="mt-0.5 inline-flex h-8 min-w-8 shrink-0 items-center justify-center rounded-lg px-2 text-xs font-bold tabular-nums"
                            style={{
                              backgroundColor: rank <= 3 ? 'var(--rank-bg)' : 'var(--bg-subtle)',
                              color: rank <= 3 ? 'var(--rank-text)' : 'var(--text-primary)',
                            }}
                            aria-label={`Rank ${rank}`}
                          >
                            #{rank}
                          </span>

                          <div className="min-w-0 flex-1">
                            <div className="mb-1.5 flex flex-wrap items-center gap-2">
                              <span
                                className="inline-flex items-center rounded-full px-2.5 py-0.5 text-[11px] font-semibold"
                                style={{
                                  backgroundColor: 'var(--accent-soft)',
                                  color: 'var(--accent-text)',
                                }}
                              >
                                {rule.category}
                              </span>
                              <span
                                className="inline-flex items-center gap-1 text-xs font-semibold tabular-nums"
                                style={{ color: 'var(--text-secondary)' }}
                              >
                                <GitBranch className="h-3.5 w-3.5" style={{ color: 'var(--accent)' }} aria-hidden="true" />
                                {rule.adoption_count.toLocaleString()} repos
                              </span>
                              <span
                                className="inline-flex items-center gap-1 text-xs tabular-nums"
                                style={{ color: 'var(--text-muted)' }}
                              >
                                <Star className="h-3 w-3" aria-hidden="true" />
                                {rule.weighted_score.toFixed(1)}
                              </span>
                            </div>

                            <h2
                              className="text-base font-bold leading-snug sm:text-[17px]"
                              style={{ color: 'var(--text-primary)' }}
                            >
                              {rule.title}
                            </h2>

                            <p className="mt-1 text-sm leading-relaxed" style={{ color: 'var(--text-secondary)' }}>
                              {rule.summary}
                            </p>

                            {/* Target Agent Badges */}
                            <div className="mt-3 flex flex-wrap items-center gap-1.5">
                              {rule.agents.map((agent) => (
                                <button
                                  key={agent}
                                  type="button"
                                  onClick={() => toggleAgent(agent)}
                                  title={`Filter by ${agent}`}
                                  className="inline-flex items-center rounded-md border px-2 py-0.5 text-[11px] font-medium transition-colors cursor-pointer"
                                  style={
                                    filters.agents.includes(agent)
                                      ? {
                                          backgroundColor: 'var(--accent-soft)',
                                          borderColor: 'var(--accent)',
                                          color: 'var(--accent-text)',
                                        }
                                      : {
                                          backgroundColor: 'var(--badge-bg)',
                                          borderColor: 'var(--border-subtle)',
                                          color: 'var(--badge-text)',
                                        }
                                  }
                                >
                                  {agent}
                                </button>
                              ))}
                            </div>
                          </div>
                        </div>

                        {/* Action Buttons */}
                        <div className="flex shrink-0 items-center gap-2 sm:flex-col sm:items-stretch">
                          <button
                            type="button"
                            onClick={() => handleCopyRule(rule)}
                            className="inline-flex min-h-9 flex-1 items-center justify-center gap-1.5 rounded-xl border px-3 py-1.5 text-xs font-semibold transition-colors cursor-pointer sm:flex-initial"
                            style={
                              isCopied
                                ? {
                                    backgroundColor: 'var(--accent)',
                                    borderColor: 'var(--accent)',
                                    color: '#ffffff',
                                  }
                                : {
                                    backgroundColor: 'var(--bg-subtle)',
                                    borderColor: 'var(--border-subtle)',
                                    color: 'var(--text-primary)',
                                  }
                            }
                          >
                            {isCopied ? (
                              <Check className="h-3.5 w-3.5" aria-hidden="true" />
                            ) : (
                              <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                            )}
                            <span>{isCopied ? 'Copied' : 'Copy Rule'}</span>
                          </button>

                          <button
                            type="button"
                            onClick={() => setSelectedRule({ rule, rank })}
                            className="inline-flex min-h-9 flex-1 items-center justify-center gap-1.5 rounded-xl border px-3 py-1.5 text-xs font-medium transition-colors cursor-pointer sm:flex-initial"
                            style={{
                              backgroundColor: 'var(--bg-surface)',
                              borderColor: 'var(--border-strong)',
                              color: 'var(--text-secondary)',
                            }}
                          >
                            <MessageSquareQuote className="h-3.5 w-3.5" aria-hidden="true" />
                            <span>Examples ({rule.examples.length})</span>
                          </button>
                        </div>
                      </div>
                    </li>
                  );
                  })}
                </ol>
              </div>
            )}
          </div>
        </div>
      </main>

      {/* Footer */}
      <footer
        className="mt-12 border-t py-6 text-center text-xs"
        style={{
          borderColor: 'var(--border-subtle)',
          color: 'var(--text-muted)',
        }}
      >
        <div className="mx-auto max-w-7xl px-4 sm:px-6">
          <p>
            <strong>RuleIndex</strong> — Automated daily semantic distillation of public{' '}
            <code>AGENTS.md</code>, <code>CLAUDE.md</code>, <code>.cursorrules</code>,{' '}
            <code>.windsurfrules</code>, <code>.clinerules</code>, <code>GEMINI.md</code>,{' '}
            <code>SKILL.md</code>, and Copilot instruction files.
          </p>
        </div>
      </footer>

      {/* Mobile Collapsible Slide-Over Filter Drawer (<dialog>) */}
      <dialog
        ref={mobileDrawerRef}
        aria-label="Filter rules"
        onClose={() => setMobileDrawerOpen(false)}
        className="mobile-filter-dialog"
        {...({ closedby: 'any' } as Record<string, string>)}
      >
        <div
          className="flex items-center justify-between border-b px-4 py-3.5"
          style={{ borderColor: 'var(--border-subtle)' }}
        >
          <span className="text-sm font-bold" style={{ color: 'var(--text-primary)' }}>
            Filter Rules
          </span>
          <button
            type="button"
            onClick={() => mobileDrawerRef.current?.close()}
            aria-label="Close filters"
            autoFocus
            className="inline-flex h-9 w-9 items-center justify-center rounded-lg border cursor-pointer"
            style={{
              backgroundColor: 'var(--bg-subtle)',
              borderColor: 'var(--border-subtle)',
              color: 'var(--text-secondary)',
            }}
          >
            <X className="h-4 w-4" aria-hidden="true" />
          </button>
        </div>

        <div className="flex-1 overflow-y-auto p-4">
          <FilterPanel
            filters={filters}
            agentCounts={agentCounts}
            categoryCounts={categoryCounts}
            hasActiveFilters={hasActiveFilters}
            onToggleAgent={toggleAgent}
            onClearAgents={clearAgents}
            onToggleCategory={toggleCategory}
            onSetMinAdoption={setMinAdoption}
            onReset={resetFilters}
          />
        </div>

        <div className="border-t p-4" style={{ borderColor: 'var(--border-subtle)' }}>
          <button
            type="button"
            onClick={() => mobileDrawerRef.current?.close()}
            className="min-h-10 w-full rounded-xl px-4 py-2 text-sm font-semibold cursor-pointer"
            style={{ backgroundColor: 'var(--accent)', color: '#ffffff' }}
          >
            Show {filteredRules.length} {filteredRules.length === 1 ? 'Rule' : 'Rules'}
          </button>
        </div>
      </dialog>

      {/* Rule Details & Real-World Variations Modal (<dialog>) */}
      <RuleDetailDialog
        rule={selectedRule?.rule ?? null}
        rank={selectedRule?.rank ?? null}
        onClose={() => setSelectedRule(null)}
        onCopyRule={handleCopyRule}
      />

      {/* Accessible Top-Layer Toast Notifications */}
      <ToastRegion message={toastMessage} onDismiss={() => setToastMessage(null)} />
    </div>
  );
}

export default App;
